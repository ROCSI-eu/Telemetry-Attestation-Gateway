"""EXPERIMENTAL / SYNTHETIC_ONLY / A0_SYNTHETIC / NOT VALIDATION OR PRODUCTION AUTHORIZATION.
Design candidate: exact package inventory, separate approval record, local staging.
No cryptographic verification, proving, networking, publication or automated retention.
"""
from pathlib import Path
from datetime import datetime,timedelta,timezone
from types import MappingProxyType
import hashlib,json,os,re,stat,sys
ROOT=Path(__file__).resolve().parent.parent
sys.path.insert(0,str(ROOT))
import inspector as i
MARKS=list(i.MARKS)
SUITE=i.SUITE
PRODUCER="366e0e7aee71fce277a20af8d1b905148aa6f31d"
VK=i.canonical.independent_verifier.EXPECTED_VK_SHA256
ACTIONS=("RETAIN","STAGE_TRANSFER","REVERIFY")
MAX_LIFETIME=timedelta(days=7) # proposed lab limit, not a production policy
MAX_RECORD=4096
DOMAIN=b"TAG_PORTABLE_EVIDENCE_EXPERIMENTAL_V1\0"
HEX=re.compile(r"[0-9a-f]{64}")
class Rejected(ValueError):pass
def need(ok,reason):
    if not ok:raise Rejected(reason)
def sha(b):return hashlib.sha256(b).hexdigest()
def enc(obj):
    return json.dumps(obj,sort_keys=True,separators=(",",":"),ensure_ascii=True).encode("ascii")
def inventory(raw):
    need(set(raw)==set(i.NAMES),"FILE_SET")
    need(all(type(raw[n]) is bytes and 0<len(raw[n])<=i.LIMITS[n] for n in i.NAMES),"FILE_SIZE")
    i.validate(raw)
    files={n:{"sha256":sha(raw[n]),"bytes":len(raw[n])} for n in sorted(i.NAMES)}
    return {"schema":"TAG_PORTABLE_INVENTORY_V1_EXPERIMENTAL","labels":MARKS.copy(),"suite":SUITE,"files":files}
def fingerprint(raw):
    return sha(DOMAIN+enc(inventory(raw)))
def load_package(folder):
    # Reuse exact Inspector 02 import and canonical CBOR parser, no suite upgrade.
    raw=i.snapshot(folder);inventory(raw);return raw
def time_value(value):
    need(type(value) is str and bool(re.fullmatch(r"\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ",value)),"TIME_FORMAT")
    try:return datetime.strptime(value,"%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)
    except ValueError:raise Rejected("TIME_FORMAT") from None
def review_check(record,expected_digest,package_digest,action,now,provenance):
    """Expected digest comes from owner decision outside package/transfer.
    This checks consistency, not identity, signature, authenticity or trusted time.
    No approval may be inferred from this function or generated by package sender.
    """
    need(action in ACTIONS,"ACTION")
    need(type(record) is bytes and 0<len(record)<=MAX_RECORD,"REVIEW_SIZE")
    need(type(expected_digest) is str and HEX.fullmatch(expected_digest) and sha(record)==expected_digest,"REVIEW_PIN")
    need(type(package_digest) is str and HEX.fullmatch(package_digest),"PACKAGE_PIN")
    try:r=i.decode(record)
    except (ValueError,TypeError,RecursionError):raise Rejected("REVIEW_SCHEMA") from None
    need(type(r) is dict and set(r)=={"schema","labels","suite","package_sha256","producer_blob","provenance_record_sha256","action","issued_utc","expires_utc","origin","scope"},"REVIEW_SCHEMA")
    need(r["schema"]=="TAG_PORTABLE_REVIEW_V1_EXPERIMENTAL" and r["labels"]==MARKS and r["suite"]==SUITE and r["producer_blob"]==PRODUCER,"REVIEW_SCHEMA")
    need(r["package_sha256"]==package_digest and r["action"]==action,"REVIEW_SCOPE")
    need(r["origin"]=="OWNER_REVIEWED_SYNTHETIC_PROVENANCE" and r["scope"]=="LOCAL_ONLY_NO_PUBLICATION","REVIEW_SCOPE")
    need(type(r["provenance_record_sha256"]) is str and HEX.fullmatch(r["provenance_record_sha256"]),"PROVENANCE_PIN")
    need(type(provenance) is bytes and 0<len(provenance)<=MAX_RECORD and sha(provenance)==r["provenance_record_sha256"],"PROVENANCE_PIN")
    try:pr=i.decode(provenance)
    except (ValueError,TypeError,RecursionError):raise Rejected("PROVENANCE_SCHEMA") from None
    need(type(pr) is dict and set(pr)=={"schema","labels","suite","package_sha256","producer_blob","source","execution_evidence_sha256","witness_retention","real_telemetry","recorded_utc","retention_not_after_utc"},"PROVENANCE_SCHEMA")
    need(pr["schema"]=="TAG_PORTABLE_PROVENANCE_V1_EXPERIMENTAL" and pr["labels"]==MARKS and pr["suite"]==SUITE and pr["package_sha256"]==package_digest and pr["producer_blob"]==PRODUCER,"PROVENANCE_SCHEMA")
    need(pr["source"]=="SYNTHETIC_INTEGER_FIXTURE" and pr["witness_retention"]=="NONE" and pr["real_telemetry"] is False,"PROVENANCE_SCOPE")
    need(type(pr["execution_evidence_sha256"]) is str and HEX.fullmatch(pr["execution_evidence_sha256"]),"EXECUTION_EVIDENCE_PIN")
    issued,expires=time_value(r["issued_utc"]),time_value(r["expires_utc"])
    recorded,cap=time_value(pr["recorded_utc"]),time_value(pr["retention_not_after_utc"])
    need(timedelta(0)<cap-recorded<=MAX_LIFETIME and recorded<=issued<expires<=cap,"RETENTION_CAP")
    need(isinstance(now,datetime) and now.tzinfo is not None and now.utcoffset()==timedelta(0),"TIME_UNAVAILABLE")
    need(timedelta(0)<expires-issued<=MAX_LIFETIME,"RETENTION_WINDOW")
    need(issued<=now<expires,"REVIEW_NOT_CURRENT")
    return MappingProxyType(r)
def inspect_for_action(raw,record,expected_review_digest,expected_package_digest,action,now,provenance):
    """Fail closed. Eligibility is not a cryptographic result or permission to launch."""
    try:
        actual=fingerprint(raw)
        need(actual==expected_package_digest,"PACKAGE_PIN")
        review_check(record,expected_review_digest,actual,action,now,provenance)
        # Existing verifier trust anchor, never the manifest's self-declared key.
        need(sha(raw["vk"])==VK,"VK_UNRECOGNIZED")
        return {"labels":MARKS.copy(),"status":"ELIGIBLE_FOR_SCOPED_ACTION_REVIEW","action":action,"cryptographic":"NOT_CHECKED","verification":"NOT_PERFORMED","source_trust":"NOT_EVALUATED","publication":"NOT_PERFORMED","decision":"NOT_MADE"}
    except (Rejected,i.Rejected) as e:
        # Fixed reasons from validators only; not arbitrary input fields.
        return {"labels":MARKS.copy(),"status":"REJECTED","reason":str(e),"cryptographic":"NOT_CHECKED","verification":"NOT_PERFORMED","publication":"NOT_PERFORMED","decision":"NOT_MADE"}
    except (ValueError,TypeError,KeyError,OSError,RecursionError):
        return {"labels":MARKS.copy(),"status":"REJECTED","reason":"INPUT_REJECTED","cryptographic":"NOT_CHECKED","verification":"NOT_PERFORMED","publication":"NOT_PERFORMED","decision":"NOT_MADE"}
def _stage_snapshot(raw,destination):
    """Private empty owner directory, fixed filenames, no overwrite.
    Caller holds exclusive cooperative ownership; not a hostile FS transaction.
    This primitive is also tested with fake bytes, never proof validity.
    """
    original=fingerprint(raw)
    fd=os.open(destination,os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW)
    created=[]
    try:
        m=os.fstat(fd)
        need(m.st_uid==os.getuid() and stat.S_IMODE(m.st_mode)==0o700,"DESTINATION_PRIVATE")
        with os.scandir(fd) as entries:need(next(entries,None) is None,"DESTINATION_NOT_EMPTY")
        for n in i.NAMES:
            f=os.open(n,os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW,0o600,dir_fd=fd)
            created.append(n)
            with os.fdopen(f,"wb") as h:
                h.write(raw[n]);h.flush();os.fsync(h.fileno())
        os.fsync(fd)
        # Verify destination still refers to opened directory; then re-import.
        s=destination.lstat()
        need((s.st_dev,s.st_ino)==(m.st_dev,m.st_ino),"DESTINATION_CHANGED")
        need(fingerprint(load_package(destination))==original,"COPY_MISMATCH")
        return original
    except BaseException:
        for n in created:
            os.unlink(n,dir_fd=fd)
        raise
    finally:os.close(fd)
def stage_for_action(raw,destination,record,expected_review_digest,expected_package_digest,action,now,provenance):
    need(action in ("RETAIN","STAGE_TRANSFER"),"ACTION")
    # Freeze caller data before authorization/copy; no path reopen.
    raw=MappingProxyType(dict(raw))
    result=inspect_for_action(raw,record,expected_review_digest,expected_package_digest,action,now,provenance)
    need(result["status"]=="ELIGIBLE_FOR_SCOPED_ACTION_REVIEW","NOT_ELIGIBLE")
    return _stage_snapshot(raw,destination)
